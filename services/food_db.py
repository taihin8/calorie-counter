def search_food(query):
    """Ищет продукты по подстроке. Возвращает список (название, ккал),
    отсортированный по точности совпадения."""
    q = query.strip().lower()
    if not q:
        return []
    exact = [(n, k) for n, k in FOODS if n == q]
    if exact:
        return exact
    starts = [(n, k) for n, k in FOODS if n.startswith(q)]
    contains = [(n, k) for n, k in FOODS if q in n]
    # дедупликация, сохраняя порядок
    seen = set()
    result = []
    for item in starts + contains:
        if item[0] not in seen:
            seen.add(item[0])
            result.append(item)
    return result[:5]

def guess_calories(name):
    """Простая эвристика: ищет по последнему осмысленному слову названия.
    Возвращает ккал/100г или None."""
    q = name.strip().lower()
    matches = search_food(q)
    if matches:
        return matches[0][1]
    # по словам с конца (отбрасываем стоп-слова)
    for word in reversed(q.split()):
        if word in ('на', 'по', 'в', 'с', 'со', 'и', 'съел', 'ем', 'кушал'):
            continue
        m = search_food(word)
        if m:
            return m[0][1]
    return None